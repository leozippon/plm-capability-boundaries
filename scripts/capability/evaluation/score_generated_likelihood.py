#!/usr/bin/env python3
"""Recompute a generating checkpoint's own likelihood on its own frozen products.

E17 asks whether the predictive information a model carries can be used to pick
better products out of its own output. The quantity that asks that question is
the model's likelihood of the sequence it produced -- and it does not exist
anywhere in this project: the frozen generation ledgers retain token *ids* and a
stop reason, never a log-probability. So it is recomputed here, on the fixed pool
the cohort stage froze, under the arm's own native rendering.

Rendering is the whole correctness risk. A ProtGPT2 sequence scored as one
unwrapped line costs 1.42 nats/token more than the same sequence in the FASTA
layout it was pretrained on, and ZymCTRL's EC tag leaks 1.73 nats if it is scored
as content instead of as a conditioning prompt. Both are larger than any
selection effect this experiment could find, so the rendering, the target mask
and the excluded marker or boundary spans all come from the audited declarations
in :mod:`src.capability.core.arms` and :mod:`src.capability.core.scoring` rather
than being spelled again here.

The score is a mean negative log-likelihood per *scored token* in the arm's own
tokenisation. It is comparable within an arm, which is all selection needs, and
it is not comparable across arms, which is why no cross-arm likelihood number is
emitted.

The pool and the scorer are separate identities. ``--arm`` names the checkpoint
that *scores*, and ``--pool-arm`` names the checkpoint whose frozen products are
scored; the second defaults to the first, which is the E17 case. They differ
only for the two ProLLaMA stages, which share one unconditional rendering family
and differ only by further training, so a cross-arm number there prices one
rendering under two checkpoints. The pool itself is never chosen by the scorer:
both cells of a stage read the same frozen members.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[3]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from src.capability.core.io import sha256_file, write_json  # noqa: E402
from src.capability.evaluation import generated_phenotype as gp  # noqa: E402
from src.capability.generation import stage_pair as sp  # noqa: E402

COMPLETION = "generated_likelihood.json"
SCHEMA_VERSION = "d1_generated_likelihood_v1"

#: The one licensed cross-arm pairing, taken from the module that declares the
#: pair rather than spelled again: the two ProLLaMA stages.
CROSS_ARM_ARMS: frozenset[str] = frozenset(sp.STAGES.values())


def load_pool(path: Path, pool_arm: str) -> list[dict[str, Any]]:
    """The frozen members the ``pool_arm`` generated, sorted by identifier.

    The scoring arm is deliberately not a parameter. Which members a cell scores
    is fixed by the cohort, so reading the pool by its generating arm is what
    keeps two scorers on byte-identical pools and makes their digests agree.
    """

    rows: list[dict[str, Any]] = []
    with Path(path).open(encoding="utf-8") as handle:
        for line in handle:
            if not line.strip():
                continue
            record = json.loads(line)
            if record.get("arm") != pool_arm or "pool" not in record.get("roles", []):
                continue
            rows.append(record)
    if not rows:
        raise SystemExit(
            f"{path} carries no pool member generated by {pool_arm!r}. Scoring an "
            "empty pool is refused rather than reported as a complete run"
        )
    identifiers = [row["id"] for row in rows]
    if len(set(identifiers)) != len(identifiers):
        raise SystemExit("the pool carries duplicate identifiers")
    return sorted(rows, key=lambda row: str(row["id"]))


def resolve_pool_arm(arm: str, pool_arm: str | None) -> str:
    """Whose products a cell scores. Defaults to the scorer's own arm (the E17 case)."""

    return pool_arm or arm


def require_cross_arm_supported(
    arm: str, pool_arm: str, rows: list[dict[str, Any]]
) -> None:
    """License cross-arm cells and require unconditional stage-pair pools, even in self cells.

    A likelihood is comparable only when the pool and the scorer share a native
    rendering. The two ProLLaMA stages do -- one bare-block family, differing
    only by further training -- so they are the one licensed pairing. Every other
    cross-arm combination would price a rendering difference as a checkpoint
    difference. Stage 2's instruction interface has no stage-1 counterpart at
    all, so a conditioned stage-1 pool is neither invented nor scored as native.
    """

    if arm == pool_arm and arm not in CROSS_ARM_ARMS:
        return
    if arm != pool_arm and {arm, pool_arm} != CROSS_ARM_ARMS:
        raise SystemExit(
            f"cross-arm scoring from pool {pool_arm!r} to scorer {arm!r} is not a "
            f"licensed pair; the only licensed pair is {sorted(CROSS_ARM_ARMS)}. "
            "Losing the comparability of the native rendering is not something "
            "this score survives"
        )
    conditioned = [
        str(row["id"])
        for row in rows
        if row.get("class_key") not in (None, "")
        or row.get("condition") not in (None, "unconditioned")
    ]
    if conditioned:
        raise SystemExit(
            f"{len(conditioned)} members of the {pool_arm!r} pool carry a "
            f"conditioning label (first {conditioned[:3]}). The stage pair shares "
            "one unconditional interface and stage 1 has no conditioned form, so a "
            "tag is never invented to make the cell square"
        )


def score_lineage(
    args: argparse.Namespace, rows: list[dict[str, Any]], pool_arm: str
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Read the declared lineage, never a fabricated panel arm or truncated block."""

    from src.capability.models.joint_lineage import BareBlockScorer, load_rung, rung

    # Stage-pair names are already lineage rung names; resolve through its table.
    declaration = rung(args.arm)
    loaded = load_rung(declaration.name, device=args.device, dtype=args.dtype)
    native = BareBlockScorer(loaded, batch_size=args.batch_size)
    rendered = native.render([str(row["sequence"]) for row in rows])
    lengths = native.token_lengths(rendered)
    limit = min(int(args.max_len), int(loaded.context))
    for row, block, width in zip(rows, rendered, lengths):
        if width > limit:
            raise SystemExit(
                f"{row['id']}: whole native rendering has {width} tokens, exceeds "
                f"effective limit {limit} (max-len={args.max_len}, context={loaded.context}); "
                "truncation is refused"
            )
        if block.n_scored_tokens < 1:
            raise SystemExit(f"{row['id']}: no scored next-token target in native span")
        if block.n_residues != int(row["length"]):
            raise SystemExit(
                f"{row['id']}: native residue count does not match frozen length"
            )
    totals = native.log_likelihood(rendered)
    scored = []
    for row, block, total in zip(rows, rendered, totals):
        nll = -float(total)
        if not math.isfinite(nll):
            raise SystemExit(
                f"{row['id']}: native negative log-likelihood is not finite"
            )
        scored.append(
            {
                "id": str(row["id"]),
                "arm": pool_arm,
                "pool_arm": pool_arm,
                "scorer_arm": args.arm,
                "class_key": row.get("class_key"),
                "length": int(row["length"]),
                "scored_tokens": int(block.n_scored_tokens),
                "nll_sum_nats": nll,
                "mean_nll_per_token_nats": nll / block.n_scored_tokens,
                "mean_nll_per_residue_nats": nll / int(row["length"]),
                "native_rendering": block.text,
                "native_token_ids": list(block.token_ids),
                "scored_target_positions": list(block.scored_positions),
            }
        )
    family = loaded.tokenisation.declaration
    return scored, {
        "loader": "src.capability.models.joint_lineage.load_rung",
        "checkpoint": str(loaded.facts["checkpoint"]),
        "loaded_facts": dict(loaded.facts),
        "loaded_context": int(loaded.context),
        "effective_max_len": limit,
        "residue_accounting": native.residue_accounting(),
        "rendering": {
            "rendering_arm": args.arm,
            "family": family.name,
            "input_format": "bare_seq_block",
            "protein_start": family.protein_start,
            "protein_end": family.protein_end,
            "context": None,
            "target_rule": family.scored_target_rule,
            "symbol_unit": native.symbol_unit,
            "score_description": native.score_description,
            "scoring_stratum": native.scoring_stratum,
            "excluded_spans": "all positions outside the residue-spelling token run, including wrappers",
            "exact_renderings_and_spans": "native_rendering, native_token_ids and scored_target_positions in annotations_jsonl",
            "ec_conditioning": "not_applicable",
        },
    }


def run(args: argparse.Namespace) -> dict[str, Any]:
    import torch

    from src.capability.core import scoring
    from src.capability.core.arms import (
        PANEL,
        Cohort,
        conditioning_boundary_ids,
        load_arm,
        rendering_marker_ids,
        tokenize_batch,
    )

    gp.require_fresh_out(args.out, COMPLETION)
    if args.arm not in PANEL and args.arm not in CROSS_ARM_ARMS:
        raise SystemExit(
            f"{args.arm!r} is not a panel member. A scoring checkpoint whose native "
            f"rendering is not declared cannot be scored; panel is {sorted(PANEL)}"
        )
    pool_arm = resolve_pool_arm(args.arm, getattr(args, "pool_arm", None))
    cross_arm = pool_arm != args.arm
    rows = load_pool(args.cohort, pool_arm)
    require_cross_arm_supported(args.arm, pool_arm, rows)
    for row in rows:
        if int(row["length"]) < 1 or int(row["length"]) != len(str(row["sequence"])):
            raise SystemExit(
                f"{row['id']}: length must be positive and match the frozen sequence"
            )
    if not args.device.startswith("cuda") or not torch.cuda.is_available():
        raise SystemExit("likelihood scoring requires an assigned CUDA GPU")

    if args.arm in CROSS_ARM_ARMS:
        scored, native = score_lineage(args, rows, pool_arm)
        return publish(args, rows, scored, pool_arm, native["rendering"], native)

    arm = load_arm(args.arm, device=args.device, dtype=args.dtype)
    labels: list[str] | None = None
    if arm.spec.input_format == "ec_conditioned":
        labels = [str(row.get("class_key") or "") for row in rows]
        missing = [row["id"] for row, label in zip(rows, labels) if not label]
        if missing:
            raise SystemExit(
                f"{args.arm} renders an EC-conditioned prompt, but {len(missing)} pool "
                f"members carry no class_key (first {missing[:3]}). Scoring them without "
                "the tag they were generated under would measure a different quantity"
            )
    cohort = Cohort(
        name=f"e17_pool_{pool_arm}",
        kind="protein",
        records=[str(row["sequence"]) for row in rows],
        min_symbols=min(int(row["length"]) for row in rows),
        max_symbols=max(int(row["length"]) for row in rows),
        metadata=(
            {
                "sampling": {"mode": "frozen_pool", "source": str(args.cohort)},
                "pool_arm": pool_arm,
                "scorer_arm": args.arm,
                "cross_arm": cross_arm,
            }
            | ({"ec_labels": labels} if labels is not None else {})
        ),
    )
    rendered = cohort.input_strings(arm)
    rule = scoring.target_rule(arm.spec.input_format, ec_conditioning="native")
    start_id, end_id = conditioning_boundary_ids(arm, ec_conditioning="native")
    markers = (
        () if arm.spec.input_format == "ec_conditioned" else rendering_marker_ids(arm)
    )

    scored: list[dict[str, Any]] = []
    truncated: list[str] = []
    with torch.inference_mode():
        for start in range(0, len(rows), args.batch_size):
            chunk = list(range(start, min(start + args.batch_size, len(rows))))
            ids, mask = tokenize_batch(
                arm, [rendered[index] for index in chunk], args.max_len
            )
            target_mask = scoring.sequence_target_mask(
                ids,
                mask,
                rule=rule,
                start_token_id=start_id,
                end_token_id=end_id,
                marker_token_ids=markers,
            )
            counts = target_mask.sum(-1).tolist()
            unscored = [
                str(rows[index]["id"])
                for index, count in zip(chunk, counts)
                if int(count) < 1
            ]
            if unscored:
                raise SystemExit(
                    f"{len(unscored)} pool members have no scored next-token target "
                    f"under the {args.arm!r} rendering (first {unscored[:3]}). A "
                    "likelihood over no token is not a likelihood, and the run is "
                    "refused rather than published"
                )
            logits = (
                arm.model(
                    input_ids=ids.to(arm.device), attention_mask=mask.to(arm.device)
                )
                .logits.float()
                .cpu()
            )
            per_sequence = scoring.per_sequence_scores(logits, logits, ids, target_mask)
            for offset, index in enumerate(chunk):
                row = rows[index]
                entry = per_sequence[offset]
                tokens = int(entry["token_count"])
                total_nll = float(entry["clean_nll_sum"])
                if tokens < 1:
                    raise SystemExit(
                        f"{row['id']}: no scored next-token target after causal shift"
                    )
                if not math.isfinite(total_nll):
                    raise SystemExit(
                        f"{row['id']}: the scored negative log-likelihood is "
                        f"{total_nll!r}, not finite. An infinite or NaN score would "
                        "rank arbitrarily and is refused rather than recorded"
                    )
                # A rendering that hit --max-len lost residues from its own tail,
                # so its mean is over a prefix and is not the score of the product.
                if int(mask[offset].sum()) >= args.max_len:
                    truncated.append(str(row["id"]))
                scored.append(
                    {
                        "id": str(row["id"]),
                        # The recorded ``arm`` is the generator, as every E17 row's was,
                        # since a generator's arm is what a later consumer joins on.
                        "arm": pool_arm,
                        "pool_arm": pool_arm,
                        "scorer_arm": args.arm,
                        "class_key": row.get("class_key"),
                        "length": int(row["length"]),
                        "scored_tokens": tokens,
                        "nll_sum_nats": total_nll,
                        "mean_nll_per_token_nats": total_nll / tokens,
                        "mean_nll_per_residue_nats": total_nll / int(row["length"]),
                    }
                )
            print(
                json.dumps({"scored": len(scored), "total": len(rows)}),
                flush=True,
            )
    if truncated:
        raise SystemExit(
            f"{len(truncated)} pool members hit --max-len {args.max_len} (first "
            f"{truncated[:3]}): their likelihood is the likelihood of a prefix, not of "
            "the product, and a selection score built on it would rank truncations. "
            "Raise --max-len"
        )

    return publish(
        args,
        rows,
        scored,
        pool_arm,
        {
            "rendering_arm": args.arm,
            "input_format": arm.spec.input_format,
            "target_rule": rule,
            "conditioning_boundary_ids": [start_id, end_id],
            "marker_token_ids": list(markers),
            "tokenisation": arm.spec.tokenisation,
            "ec_conditioning": "native" if labels is not None else "not_applicable",
        },
    )


def publish(
    args: argparse.Namespace,
    rows: list[dict[str, Any]],
    scored: list[dict[str, Any]],
    pool_arm: str,
    rendering: dict[str, Any],
    native: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Publish either native route with the same pool and scorer identities."""

    cross_arm = pool_arm != args.arm
    sidecar = args.out / "generated_likelihood.jsonl"
    sidecar.write_text(
        "".join(json.dumps(row, sort_keys=True) + "\n" for row in scored),
        encoding="utf-8",
    )
    values = [row["mean_nll_per_token_nats"] for row in scored]
    record = {
        "schema_version": SCHEMA_VERSION,
        "status": "complete",
        "created_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "arm": args.arm,
        "pool_arm": pool_arm,
        "generator_arm": pool_arm,
        "scorer_arm": args.arm,
        "cross_arm": cross_arm,
        "n_scored": len(scored),
        "n_pool_members": len(rows),
        "cohort": str(args.cohort),
        "cohort_sha256": sha256_file(args.cohort),
        "pool_digest": gp.cohort_digest(rows),
        "rendering": rendering,
        "device": args.device,
        "dtype": args.dtype,
        "max_len": int(args.max_len),
        "batch_size": int(args.batch_size),
        "mean_nll_per_token_nats": {
            "min": min(values),
            "max": max(values),
            "mean": sum(values) / len(values),
        },
        "annotations_jsonl": str(sidecar),
        "annotations_sha256": sha256_file(sidecar),
        "interpretation": (
            (
                "mean negative log-likelihood per scored token the scorer arm assigns "
                f"to products generated by {pool_arm!r}, under the scorer's own native "
                "rendering and tokenisation. The scorer did not generate these products "
                "and the two arms' nats per token are not comparable; what the cell "
                "supports is one scorer's ordering of one frozen pool, and the "
                "generator arm is recorded beside it"
            )
            if cross_arm
            else (
                "mean negative log-likelihood per scored token under the arm's own "
                "native rendering and tokenisation. Comparable within this arm, which "
                "is what selection needs; not comparable to another arm's nats per token"
            )
        ),
    }
    if native is not None:
        record.update(
            {key: value for key, value in native.items() if key != "rendering"}
        )
    write_json(args.out / COMPLETION, record)
    return record


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--cohort", type=Path, required=True, help="the frozen evaluation cohort JSONL"
    )
    parser.add_argument(
        "--arm",
        required=True,
        help="the panel checkpoint or ProLLaMA lineage rung used to score",
    )
    parser.add_argument(
        "--pool-arm",
        default=None,
        help=(
            "the arm whose frozen products are scored; defaults to --arm (the E17 case). "
            "Cross-arm is licensed only for the ProLLaMA stage pair"
        ),
    )
    parser.add_argument("--dtype", default="bfloat16")
    parser.add_argument("--max-len", type=int, default=1024)
    parser.add_argument("--batch-size", type=int, default=8)
    parser.add_argument("--device", default="cuda:0")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    if args.batch_size < 1 or args.max_len < 2:
        parser.error("--batch-size must be positive and --max-len at least two")
    record = run(args)
    print(
        json.dumps(
            {key: record[key] for key in ("status", "arm", "n_scored")}, sort_keys=True
        )
    )


if __name__ == "__main__":
    main()
