def resources(device: str) -> dict:
    """Observed memory, disk, CPU and thread state of the running machine."""

    memory = {}
    for line in Path('/proc/meminfo').read_text(encoding='utf-8').splitlines():
        for name in ('MemTotal', 'MemAvailable'):
            if line.startswith(f'{name}:'):
                memory[name] = int(line.split()[1]) * 1024
    return {'executable': sys.executable, 'device': device, 'cpus': os.cpu_count(),
            'memory_total_bytes': memory.get('MemTotal'),
            'memory_available_bytes': memory.get('MemAvailable'),
            'disk_free_bytes': shutil.disk_usage(ROOT).free,
            'threads': {v: os.environ[v] for v in
                        ('OMP_NUM_THREADS', 'OPENBLAS_NUM_THREADS', 'MKL_NUM_THREADS')}}


def preflight_resources(record: dict) -> None:
    """Refuse a machine that cannot hold the fit and its bootstrap. Fail loudly.

    The three floors exist so that a run which starts under memory pressure or on
    a full disk fails here with the measured numbers rather than midway through a
    fold, where the failure would be indistinguishable from a data defect.
    """

    problems = []
    available = record.get('memory_available_bytes')
    if available is None or available < RESOURCE_MIN_MEMORY_BYTES:
        problems.append(f'MemAvailable {available} below {RESOURCE_MIN_MEMORY_BYTES}')
    if record['disk_free_bytes'] < RESOURCE_MIN_DISK_BYTES:
        problems.append(f"disk free {record['disk_free_bytes']} below {RESOURCE_MIN_DISK_BYTES}")
    if not record['cpus'] or record['cpus'] < RESOURCE_MIN_CPUS:
        problems.append(f"cpus {record['cpus']} below {RESOURCE_MIN_CPUS}")
    if problems:
        raise SystemExit('resource preflight failed: ' + '; '.join(problems))


def group_gene_by_unit(root: Path) -> dict[str, str]:
    """Wild-type digest to gene, from the preparation's own state inventory.

    The reader's base path is imported rather than restated, so the inventory
    this reads is exactly the one the admitted cohort was built from.
    """

    base = root / 'results/extensions' / sources.MEASUREMENT / 'cellular-fitness/final'
    inventory = json.loads((base / 'state-inventory.json').read_text(encoding='utf-8'))['states']
    return {record['sequence_sha256']: record['gene']
            for record in inventory if record['role'] == 'WT'}


def tail_percentile(labels: np.ndarray) -> np.ndarray:
    """Empirical fitness percentile of each label inside its own group.

    Higher oriented label is higher fitness, so the percentile is the average
    rank over the group size. It is a property of the group's own measured
    distribution and uses no model quantity.
    """

    labels = np.asarray(labels, dtype=np.float64)
    if not labels.size or not np.isfinite(labels).all():
        raise ValueError('a percentile is defined only on a nonempty finite label vector')
    return rankdata(labels, method='average') / labels.size


def select_top_k(prediction: np.ndarray, row_ids: np.ndarray, k: int) -> np.ndarray | None:
    """Indices of the ``k`` largest predictions, or ``None`` if undefined.

    Ties at the boundary are broken by ascending row id, which is an identity
    string: the rule is declared, deterministic and reads no label. An undefined
    selection is returned as ``None`` rather than padded or truncated, and a
    caller must not substitute a value for it.
    """

    prediction = np.asarray(prediction, dtype=np.float64)
    row_ids = np.asarray(row_ids)
    if prediction.ndim != 1 or prediction.size != row_ids.size:
        raise ValueError('prediction and identity vectors must align')
    if k <= 0:
        raise ValueError('the tail budget must be positive')
    if prediction.size < k or not np.isfinite(prediction).all():
        return None
    return np.lexsort((row_ids, -prediction))[:k]


def group_tail_outcome(prediction: np.ndarray, labels: np.ndarray,
                       row_ids: np.ndarray, k: int) -> dict | None:
    """Mean measured percentile of one group's selected tail, or ``None``."""

    selected = select_top_k(prediction, row_ids, k)
    if selected is None:
        return None
    return {'outcome': float(tail_percentile(labels)[selected].mean()),
            'selected': [str(value) for value in np.asarray(row_ids)[selected]]}


def arm_tail_contributions(arm: str, seeds, baseline_by_seed: dict, augmented_by_seed: dict,
                           labels: np.ndarray, row_ids: np.ndarray, groups: np.ndarray,
                           k: int = K) -> tuple[dict, list[dict]]:
    """Group-level tail cells and the selections behind them, for one arm.

    ``baseline_by_seed`` and ``augmented_by_seed`` map a split seed to the OOF
    prediction vector of that design. A group cell is null whenever any declared
    seed's selection is undefined: seeds are averaged as sensitivity analyses
    over the whole declared set, so averaging over the subset that happened to
    resolve would report a design the frozen panel never fitted. Nothing is
    replaced by zero.
    """

    labels = np.asarray(labels, dtype=np.float64)
    row_ids = np.asarray(row_ids)
    groups = np.asarray(groups)
    cells: dict[str, dict] = {}
    membership: list[dict] = []
    for group in sorted({str(value) for value in groups.tolist()}):
        mask = groups == group
        group_labels, group_ids = labels[mask], row_ids[mask]
        baseline_values, augmented_values = [], []
        group_membership = []
        resolved = True
        for seed in seeds:
            baseline = group_tail_outcome(np.asarray(baseline_by_seed[seed])[mask],
                                          group_labels, group_ids, k)
            augmented = group_tail_outcome(np.asarray(augmented_by_seed[seed])[mask],
                                           group_labels, group_ids, k)
            if baseline is None or augmented is None:
                resolved = False
                break
            baseline_values.append(baseline['outcome'])
            augmented_values.append(augmented['outcome'])
            group_membership.append({'arm': arm, 'seed': int(seed), 'group': group,
                                     'baseline_rows': baseline['selected'],
                                     'augmented_rows': augmented['selected']})
        if not resolved:
            cells[group] = {'baseline': None, 'augmented': None, 'contrast': None, 'seeds': []}
            continue
        membership.extend(group_membership)
        base = float(np.mean(baseline_values))
        augmented_mean = float(np.mean(augmented_values))
        cells[group] = {'baseline': base, 'augmented': augmented_mean,
                        'contrast': augmented_mean - base, 'seeds': [int(s) for s in seeds]}
    return cells, membership


def descriptive_levels(labels: np.ndarray, row_ids: np.ndarray, groups: np.ndarray,
                       k: int = K) -> dict:
    """Uniform-random expected level and best-k-by-label oracle, per group.

    Descriptive only: the random level is the group's own mean percentile, which
    is the expectation of the mean percentile of a uniformly drawn k-subset, and
    the oracle is the mean percentile of the true best k. A random contrast is
    exactly zero by construction and is therefore not bootstrapped.
    """

    labels = np.asarray(labels, dtype=np.float64)
    row_ids = np.asarray(row_ids)
    groups = np.asarray(groups)
    per_group = {}
    for group in sorted({str(value) for value in groups.tolist()}):
        mask = groups == group
        percentiles = tail_percentile(labels[mask])
        selected = select_top_k(labels[mask], row_ids[mask], k)
        per_group[group] = {
            'rows': int(mask.sum()),
            'random_expected': float(percentiles.mean()),
            'oracle_best_k': None if selected is None else float(percentiles[selected].mean())}
    def equal(key):
        values = [per_group[group][key] for group in sorted(per_group)]
        return None if any(value is None for value in values) else float(np.mean(values))
    return {'per_group': per_group, 'random_expected': equal('random_expected'),
            'oracle_best_k': equal('oracle_best_k'),
            'note': ('a uniformly random k-subset has expected contrast zero, so only the absolute '
                     'levels are reported and neither level is inferential')}


def shared_band(cells: dict, arms, groups) -> dict:
    """One shared-draw simultaneous band over the ten arms, plus marginals.

    Reuses the frozen panel's own band function by restating each group's tail
    contrast as that arm's single increment cell, so the verdict rule is the E05
    one rather than a second implementation.
    """

    missing = [(arm, group) for arm in arms for group in groups
               if cells[arm][group]['contrast'] is None]
    if missing:
        return {'status': 'unavailable', 'missing_cells': [{'arm': a, 'group': g}
                                                            for a, g in missing],
                'reason': ('a group contributes no tail contrast for these arms, so the shared band '
                           'is undefined; the matrix is not repaired and no value is imputed')}
    flat = [{'arm': arm, 'background': group, 'group': group,
             'increment': cells[arm][group]['contrast']}
            for arm in arms for group in groups]
    band, resolved = breadth.arm_band(flat, arms, groups)
    return {'status': 'complete', 'inference': band, 'arms': resolved,
            'resolved_positive': sum(1 for row in resolved if row['resolved_positive']),
            'resolved_negative': sum(1 for row in resolved if row['resolved_negative']),
            'family': (f'one shared resample of the {len(groups)} independent groups covers all '
                       f'{len(arms)} ranking arms simultaneously; the pointwise quantiles are '
                       'reported beside it')}


def load_reference(path: Path, admission: dict, qualification: Path, profiles_path: Path,
                   arms, groups) -> dict:
    """The frozen E05 panel, checked against the inputs this run was handed.

    Every identity that could silently mix two runs is compared here: the
    qualification digest, the profile file digest, the arm list, the split seeds
    and the group list. A reference that does not describe these inputs is an
    error, not a tolerance.
    """

    reference = json.loads(Path(path).read_text(encoding='utf-8'))
    failures = []
    if reference.get('cohort') != COHORT or reference.get('endpoint') != ENDPOINT:
        failures.append(f"reference is {reference.get('cohort')}/{reference.get('endpoint')}, "
                        f'not {COHORT}/{ENDPOINT}')
    if reference.get('status') != 'admitted':
        failures.append(f"reference status is {reference.get('status')!r}")
    if reference.get('model_column') != 'M_rank' or reference.get('metric') != 'spearman':
        failures.append('reference is not the ranking endpoint with the standardized-rank column')
    if list(reference.get('qualified_controls', ())) != list(BASELINE):
        failures.append(f"reference qualified set is {reference.get('qualified_controls')}, not the "
                        f'frozen evolutionary baseline {list(BASELINE)}')
    if sorted(reference.get('arms', ())) != sorted(arms):
        failures.append(f'reference arms {reference.get("arms")} are not this run\'s arms')
    if list(reference.get('groups', ())) != list(groups):
        failures.append('reference independent groups are not this run\'s groups')
    if list(reference.get('split_seeds', ())) != list(breadth.SPLIT_SEEDS):
        failures.append('reference split seeds are not the frozen ones')
    if reference.get('qualification_sha256') != sha256_file(qualification / 'cohort_qualification.json'):
        failures.append('reference was fitted on a different qualification run')
    if reference.get('profiles', {}).get('sha256') != sha256_file(profiles_path):
        failures.append('reference was fitted on a different profile file')
    if reference.get('support', {}).get('rows') != admission['support']['rows']:
        failures.append('reference support rows disagree with the admission')
    if failures:
        raise SystemExit('reference panel is not the frozen E05 record: ' + '; '.join(failures))
    return reference


def replay_oof(rows, blocks, scores, qualified, arms, seeds, groups, backgrounds, target):
    """Regenerate the frozen E05 out-of-fold predictions and their audit trail.

    The same design, the same nested held-out-group partition and the same ridge
    path the panel used: this is the panel's own fit re-run, not a second fitting
    engine.
    """

    predictions: dict = {}
    design_digests: dict = {}
    target_digests: dict = {}
    alphas: dict = {}
    cells: list[dict] = []
    for arm in arms:
        model = breadth.model_block(rows, scores[arm], backgrounds)
        arm_blocks = {**blocks, 'M': model['M_rank']}
        baseline_design = breadth.design(arm_blocks, list(qualified))
        augmented_design = breadth.design(arm_blocks, [*qualified, 'M'])
        design_digests[arm] = breadth.array_digest(augmented_design)
        for seed in seeds:
            signature = breadth.outer_signature(groups, seed)
            baseline, baseline_records = breadth.fold_predictions(
                baseline_design, target, backgrounds, groups, signature)
            augmented, augmented_records = breadth.fold_predictions(
                augmented_design, target, backgrounds, groups, signature)
            predictions.setdefault(arm, {})[seed] = {'baseline': baseline, 'augmented': augmented}
            target_digests.setdefault(arm, {})[seed] = breadth.array_digest(target)
            alphas.setdefault(arm, {})[seed] = {
                'control': [record['alpha'] for record in baseline_records],
                'augmented': [record['alpha'] for record in augmented_records]}
            metrics = breadth.background_metrics(
                {'control': baseline, 'control_plus_model': augmented}, target, backgrounds, groups,
                metric='spearman')
            for record in metrics:
                for key in ('control', 'control_plus_model'):
                    value = record['scores'][key]
                    if value is None or not np.isfinite(value):
                        raise SystemExit(
                            f"{arm}/{seed}/{record['background']}: undefined rank correlation")
                cells.append({'arm': arm, 'seed': int(seed), 'background': record['background'],
                              'group': record['group'], 'rows': record['rows'],
                              'control': record['scores']['control'],
                              'control_plus_model': record['scores']['control_plus_model'],
                              'increment': (record['scores']['control_plus_model']
                                            - record['scores']['control'])})
    return {'predictions': predictions, 'design_digests': design_digests,
            'target_digests': target_digests, 'alphas': alphas, 'cells': cells}


def verify_replay(reference: dict, arms, seeds, replay: dict) -> dict:
    """Compare the replay to the frozen panel, or fail fast with named checks."""

    failures: list[str] = []
    worst = 0.0

    def compare(label: str, ours, frozen) -> None:
        nonlocal worst
        if ours is None or not np.isfinite(ours) or not np.isfinite(frozen):
            failures.append(f'{label}: nonfinite replay or reference value')
            return
        error = abs(float(ours) - float(frozen))
        worst = max(worst, error)
        if error > REPLAY_TOLERANCE:
            failures.append(f'{label}: |{ours} - {frozen}| = {error} exceeds {REPLAY_TOLERANCE}')

    for arm in arms:
        for seed in seeds:
            frozen = reference['fits'][arm][str(seed)]
            if replay['design_digests'][arm] != frozen['design_sha256']:
                failures.append(f'{arm}/{seed}: augmented design digest does not replay')
            if replay['target_digests'][arm][seed] != frozen['target_sha256']:
                failures.append(f'{arm}/{seed}: ranking target digest does not replay')
            if replay['alphas'][arm][seed]['control'] != frozen['alphas_control']:
                failures.append(f'{arm}/{seed}: control ridge penalties do not replay')
            if replay['alphas'][arm][seed]['augmented'] != frozen['alphas_augmented']:
                failures.append(f'{arm}/{seed}: augmented ridge penalties do not replay')
    frozen_cells = {(row['arm'], int(row['seed']), row['background']): row
                    for row in reference['per_background']}
    ours_cells = {(row['arm'], row['seed'], row['background']): row for row in replay['cells']}
    if set(ours_cells) != set(frozen_cells):
        failures.append('per-background cell memberships differ from the reference')
    for key in sorted(set(ours_cells) & set(frozen_cells)):
        compare(f'{key[0]}/{key[1]}/{key[2]} control', ours_cells[key]['control'],
                frozen_cells[key]['control'])
        compare(f'{key[0]}/{key[1]}/{key[2]} augmented', ours_cells[key]['control_plus_model'],
                frozen_cells[key]['control_plus_model'])
    band, resolved = breadth.arm_band(replay['cells'], arms, reference['groups'])
    frozen_band = reference['inference']
    if band['shared_draw_sha256'] != frozen_band['shared_draw_sha256']:
        failures.append('the bootstrap group resample is not the frozen one')
    compare('simultaneous critical value', band['critical_max_absolute_deviation'],
            frozen_band['critical_max_absolute_deviation'])
    for index, arm in enumerate(arms):
        compare(f'{arm} panel band point', band['point'][index], frozen_band['point'][index])
        compare(f'{arm} panel band lower', band['simultaneous'][index][0],
                frozen_band['simultaneous'][index][0])
    frozen_results = {row['arm']: row for row in reference['arm_results']}
    for row in resolved:
        compare(f"{row['arm']} resolved_positive", float(row['resolved_positive']),
                float(frozen_results[row['arm']]['resolved_positive']))
    return {'verified': not failures, 'failures': failures, 'tolerance': REPLAY_TOLERANCE,
            'max_absolute_deviation': worst, 'cells_compared': len(ours_cells),
            'digests_compared': 4 * len(arms) * len(seeds),
            'rule': ('the augmented design digest, the ranking target digest, the ridge penalties, '
                     'every per-background rank correlation and the panel band must reproduce the '
                     'frozen fit-panel10 record; digests exactly and floats within tolerance')}


def cohort_eligibility(root: Path, admission: dict, groups_assignment: dict,
                       grouping: dict, rows) -> dict:
    """Confirm the nine frozen human SGE groups and nothing else.

    The admitted support, the frozen grouping record and the freshly re-derived
    grouping must agree, the nine units must map onto the declared genes, and
    units and groups must be in bijection. An unlisted target, a merged group or
    a drifting support is an error; the analysis does not subset silently.
    """

    genes = group_gene_by_unit(root)
    failures = []
    if admission.get('status') != 'admitted' or not admission.get('ranking_licensed'):
        failures.append('the cellular-fitness cohort is not admitted for ranking')
    if admission.get('cohort') != COHORT:
        failures.append(f"admission is for {admission.get('cohort')!r}")
    groups_assignment = {unit: str(group) for unit, group in groups_assignment.items()}
    if groups_assignment != {unit: str(group) for unit, group in grouping['assignment'].items()}:
        failures.append('the frozen group assignment does not match the re-derived one')
    units = sorted({row.unit for row in rows})
    names = []
    for unit in units:
        gene = genes.get(unit)
        if gene is None:
            failures.append(f'unit {unit[:12]} maps to no prepared wild type')
        elif gene not in FROZEN_GENES:
            failures.append(f'unit {unit[:12]} is gene {gene}, outside the frozen target set')
        else:
            names.append(gene)
    if sorted(names) != sorted(FROZEN_GENES):
        failures.append(f'retained genes {sorted(names)} are not the frozen nine')
    if len(set(groups_assignment.values())) != len(FROZEN_GENES) or len(units) != len(FROZEN_GENES):
        failures.append(f'{len(units)} units in {len(set(groups_assignment.values()))} groups, '
                        f'not {len(FROZEN_GENES)} of each')
    if failures:
        raise SystemExit('cohort eligibility failed: ' + '; '.join(failures))
    # The paralogs are read out of the frozen assignment, not compared: with nine
    # units in nine distinct groups each unit is its own group, so the three
    # paralogs cannot share one. Their relatedness below the frozen threshold is
    # recorded as a limitation rather than re-qualified.
    unit_by_gene = {genes[unit]: unit for unit in units}
    paralog_groups = {gene: groups_assignment[unit_by_gene[gene]] for gene in PARALOGS}
    return {'genes': sorted(set(names)), 'units': len(units),
            'groups': len(set(groups_assignment.values())),
            'paralog_dependence': {
                'genes': list(PARALOGS), 'groups': paralog_groups,
                'distinct_groups': len(set(paralog_groups.values())),
                'source': ('the frozen E05 group assignment; no sequence comparison is run and no '
                           'pairwise identity is claimed'),
                'conclusion': ('the three RAD51 paralogs occupy three distinct frozen groups; their '
                               'relatedness below the frozen 30%/80% threshold remains an accepted '
                               'independence limitation')},
            'excluded': ('activity, binding, SKEMPI, membrane, matched and every unlisted SGE '
                         'target; only the nine frozen human SGE groups are analysed')}


def run(args) -> dict:
    """The whole analysis, from validated inputs to the completion record."""

    started = time.monotonic()
    qualification = Path(args.qualification)
    admission_path = qualification / 'cohorts' / f'{COHORT}.json'
    groups_path = qualification / 'groups' / f'{COHORT}.json'
    plan_path = qualification / 'profile-plan.json'
    for path in (qualification / 'cohort_qualification.json', admission_path, groups_path, plan_path):
        if not path.is_file():
            raise SystemExit(f'missing required input: {path}')
    admission = json.loads(admission_path.read_text(encoding='utf-8'))
    frozen_groups = json.loads(groups_path.read_text(encoding='utf-8'))['assignment']

    # ``qualify`` is annotated as returning its record alone although it returns the
    # record, the retained rows and the grouping; the cast keeps this call site
    # honest without editing the frozen module.
    record, rows, grouping = cast(
        tuple[dict, list, dict],
        breadth.qualify(sources.READERS[COHORT](args.root), args.runtime, floor=args.floor))
    if record['rows_sha256'] != admission['rows_sha256']:
        raise SystemExit('the re-derived support does not match the admitted digest')
    missing = sorted({row.unit for row in rows} - set(frozen_groups))
    if missing:
        raise SystemExit(f'{len(missing)} units carry no admitted group')
    eligibility = cohort_eligibility(args.root, admission, frozen_groups, grouping, rows)

    backgrounds = np.asarray([row.background for row in rows])
    groups = np.asarray([frozen_groups[row.unit] for row in rows])
    labels = np.asarray([row.oriented_label() for row in rows], dtype=np.float64)
    row_ids = np.asarray([row.row_id for row in rows])
    if not np.isfinite(labels).all():
        raise SystemExit('the admitted labels are not all finite')
    target = breadth.rerank(labels, backgrounds)

    plan = json.loads(plan_path.read_text(encoding='utf-8'))
    wildtypes = {entry['name']: entry['wildtype'] for entry in plan['backgrounds']}
    profiles, _ = load_profiles(args.profiles, wildtypes)
    blocks, census = breadth.prune_constant_columns(breadth.control_blocks(rows, profiles))
    scores = breadth.read_arm_scores(args.scores)
    arms = sorted(scores)
    seeds = list(breadth.SPLIT_SEEDS)
    ordered_groups = sorted({str(group) for group in groups.tolist()})
    support_by_group = Counter(groups.tolist())
    if support_by_group != Counter({group: GROUP_CAP for group in ordered_groups}):
        raise SystemExit(f'per-group support {dict(support_by_group)} is not the frozen '
                         f'{GROUP_CAP} variants per group')
    genes = group_gene_by_unit(args.root)

    reference = load_reference(args.reference, admission, qualification, args.profiles, arms,
                               ordered_groups)
    replay = replay_oof(rows, blocks, scores, BASELINE, arms, seeds, groups, backgrounds, target)
    verification = verify_replay(reference, arms, seeds, replay)
    if not verification['verified']:
        raise SystemExit('the frozen E05 ranking panel does not replay: '
                         + '; '.join(verification['failures'][:5]))

    contributions: dict = {}
    membership: list[dict] = []
    for arm in arms:
        cells, records = arm_tail_contributions(
            arm, seeds,
            {seed: replay['predictions'][arm][seed]['baseline'] for seed in seeds},
            {seed: replay['predictions'][arm][seed]['augmented'] for seed in seeds},
            labels, row_ids, groups)
        contributions[arm] = cells
        membership.extend(records)
    primary = shared_band(contributions, arms, ordered_groups)
    primary['k'] = K
    primary['k_rule'] = f'ceil({SELECTION_FRACTION} * {GROUP_CAP}) = {K}'
    primary['outcome'] = ('mean empirical fitness percentile within the group of the k variants '
                          'with the largest out-of-fold prediction; higher is better')
    primary['aggregation'] = ('seed mean within group, then equal groups; one shared group resample')
    primary['group_contributions'] = {arm: contributions[arm] for arm in arms}
    primary['independence_floor'] = breadth.bootstrap_unit_floor(len(ordered_groups))

    record_out = {
        'schema': SCHEMA, 'stage': 'analyse_cellular_fitness_tail_selection', 'status': 'complete',
        'completed_utc': datetime.now(timezone.utc).isoformat(),
        'cohort': COHORT, 'endpoint': ENDPOINT,
        'phenotype': admission.get('phenotype'),
        'baseline': {'qualified_controls': list(BASELINE),
                     'requalified': False,
                     'source': ('the frozen E05 qualified set, validated against the reference '
                                'panel and never re-selected on this endpoint')},
        'gene_targets': {unit: {'gene': genes[unit], 'group': frozen_groups[unit]}
                         for unit in sorted({row.unit for row in rows})},
        'eligibility': eligibility,
        'arms': arms, 'split_seeds': seeds, 'groups': ordered_groups,
        'support': {'rows': len(rows), 'groups': len(ordered_groups), 'units': len({r.unit for r in rows}),
                    'rows_sha256': record['rows_sha256']},
        'control_column_census': census,
        'replay': verification,
        'primary': primary,
        'descriptive': descriptive_levels(labels, row_ids, groups),
        'selection_rule': ('k largest out-of-fold predictions per group; boundary ties broken by '
                           'ascending row id, an identity string read label-blind'),
        'percentile_rule': ('average rank of the oriented fitness label within the group divided by '
                            'the group size; higher oriented label is higher fitness'),
        'oof_selection': membership,
        'bootstrap': {'draws': breadth.BOOTSTRAP_DRAWS, 'seed': breadth.BOOTSTRAP_SEED,
                      'family': f'{len(arms)} arms under one shared group resample'},
        'sources': {
            'qualification': {'path': str(qualification),
                              'cohort_qualification_sha256': sha256_file(
                                  qualification / 'cohort_qualification.json'),
                              'admission_sha256': sha256_file(admission_path),
                              'groups_sha256': sha256_file(groups_path),
                              'profile_plan_sha256': sha256_file(plan_path)},
            'profiles': {'path': str(args.profiles), 'sha256': sha256_file(args.profiles)},
            'reference': {'path': str(args.reference), 'sha256': sha256_file(args.reference)},
            'scores': [{'path': str(directory),
                        'phenotype_scoring_sha256': sha256_file(Path(directory)
                                                                / 'phenotype_scoring.json')}
                       for directory in args.scores],
            'score_binding': ('each scoring completion record carries the digest of every state '
                              'archive it names, so hashing the record binds the model outputs'),
            'state_inventory_sha256': sha256_file(
                args.root / 'results/extensions' / sources.MEASUREMENT
                / 'cellular-fitness/final/state-inventory.json')},
        'limitations': LIMITATIONS,
        'seconds': time.monotonic() - started,
        'resources': resources(args.device),
    }
    return record_out


def parse_args(argv=None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--qualification', type=Path, required=True,
                        help='completed qualify_phenotype_cohorts output directory')
    parser.add_argument('--reference', type=Path, required=True,
                        help='frozen fit-panel10 cellular_fitness_sge-ranking panel record')
    parser.add_argument('--profiles', type=Path, required=True,
                        help='profile_features npz over the qualification profile plan; the '
                             'frozen baseline includes the evolutionary-profile blocks')
    parser.add_argument('--scores', type=Path, action='append', required=True,
                        help='completed score_phenotype_states output directory; repeatable')
    parser.add_argument('--out', type=Path, required=True,
                        help='output directory; an empty one is accepted, one holding a previous '
                             'run is refused')
    parser.add_argument('--device', default='cpu', help='accepted for queue compatibility')
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--runtime', type=Path, default=None)
    parser.add_argument('--floor', type=int, default=breadth.INDEPENDENCE_FLOOR)
    return parser.parse_args(argv)


def main(argv=None) -> int:
    args = parse_args(argv)
    args.root = Path(args.root).resolve()
    observed = resources(args.device)
    try:
        preflight_resources(observed)
    except SystemExit as error:
        print(json.dumps({'status': 'refused', 'reason': str(error), 'resources': observed}))
        return 2
    try:
        out = breadth.prepare_output(args.out, COMPLETION)
    except ValueError as error:
        raise SystemExit(str(error))
    args.out = out
    args.runtime = (args.runtime or out / 'runtime').resolve()
    started = time.monotonic()
    write_json(out / 'resource-start.json',
               {'status': 'running', 'started_utc': datetime.now(timezone.utc).isoformat(),
                'resources': observed, 'argv': sys.argv[1:]})
    try:
        record = run(args)
    except SystemExit:
        raise
    except Exception as error:  # a failure is written out, never swallowed
        write_json(out / 'failure.json',
                   {'status': 'failed', 'error': f'{type(error).__name__}: {error}',
                    'seconds': time.monotonic() - started})
        raise
    write_json(out / COMPLETION, record)
    write_json(out / 'resource-end.json',
               {'status': 'complete', 'resources': resources(args.device),
                'seconds': time.monotonic() - started})
    print(json.dumps({
        'out': str(out), 'groups': len(record['groups']), 'arms': len(record['arms']),
        'replay': record['replay']['verified'],
        'primary': {'status': record['primary']['status'],
                    'resolved_positive': record['primary'].get('resolved_positive'),
                    'resolved_negative': record['primary'].get('resolved_negative')},
        'seconds': record['seconds']}, indent=1))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())