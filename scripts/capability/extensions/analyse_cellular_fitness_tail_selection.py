#!/usr/bin/env python3
"""Retrospective tail selection on the measured endogenous-fitness cohort.

One question, asked of an already measured cohort and an already fitted panel:
among the variants a checkpoint's likelihood would put in a small top tail of
each independent group, is the measured fitness percentile better than the
evolutionary baseline's top tail?

No sequences are newly scored or downloaded. The out-of-fold predictions are
regenerated by refitting the frozen E05 ranking design with the same method -- the
same admission support, the same qualified control set, the same nested
held-out-group partition and the same split seeds -- and the run refuses to
continue unless the replayed design and target digests, the per-background rank
correlations and the panel band reproduce the frozen ``fit-panel10`` record
within tolerance. A tail result computed on predictions that are not the frozen
ones is not the same experiment, so the check is a precondition, not a report.

The primary contrast is the augmented design minus the frozen qualified
evolutionary baseline, group-equal, with the split seeds averaged inside each
group. The variant budget is one declared number, ``k = ceil(0.02 * 256) = 6``
of the 256-variant per-group cap. One simultaneous band covers all ten ranking
arms under one shared resample of the nine independent groups, with the
pointwise quantiles reported beside it. The uniform-random expected level and
the best-six-by-measured-label oracle are descriptive references only and carry
no inference.

A cell whose selection or rank is not defined is reported null and never
imputed; if any group contributes no contrast the shared band is reported
unavailable rather than computed over a repaired matrix.
"""
