def _shannon_entropy_bits(seq: str) -> float:
    cnt = collections.Counter(seq)
    n = len(seq)
    return -sum((c / n) * math.log2(c / n) for c in cnt.values())


def test_esm3_seqonly_r1_and_production_eval_artifacts() -> None:
    """Verify ESM3-1.4B R1 ladder/conditionals evaluation and cached R1/R2/R3 production artifacts."""
    esm3_dir = ROOT / "results/shared/external_baseline/20261120213246_766da841c1a8/esm3_1_4b_r123_b4"
    if not (esm3_dir / "esm3_r123_seqonly.json").is_file():
        pytest.skip("esm3_1_4b_r123_b4 not present locally")

    ladder, matched = _eval_r1_ladder_and_matched(esm3_dir, ROOT)
    assert ladder["n_assays"] == 201
    assert ladder["n_variants"] == 25728
    assert np.isfinite(ladder["summary"]["model_spearman"]["mean"])
    assert np.isfinite(ladder["bidirectional_ridge"]["paired_increments"]["forward_M_given_PEG"]["spearman_increment"]["mean"])
    assert set(matched["tiers"]) >= {"T_open", "T_match"}

    cond = _eval_r1_family_conditionals(esm3_dir, ROOT)
    assert cond["n_eval_units"] == 64
    assert set(cond["conservation_quartiles_var_to_cons"]) == {"Q1", "Q2", "Q3", "Q4"}
    assert np.isfinite(cond["evaluation_summary"]["minus_profile"]["mean"])

    # Verify production artifacts generated by fit_general_plm_summary.py if present.
    eval_path = ROOT / "results/extensions/general_plm_20261120/esm3_1_4b_seqonly_eval.json"
    summary_path = ROOT / "results/extensions/general_plm_20261120/general_plm_summary.json"
    if eval_path.is_file():
        assert eval_path.with_name(eval_path.name + ".sha256").is_file()
        edoc = json.loads(eval_path.read_text(encoding="utf-8"))
        assert edoc["arm"] == "esm3-1.4b"
        assert set(edoc["r2_phenotypes_and_readouts"]["lanes"]) == {
            "abundance",
            "stability",
            "phenotype",
        }
        assert edoc["r3_pairwise_and_contacts"]["pairwise_cycles"]["n_cycles"] == 8192
        assert "M_cycle" in edoc["r3_pairwise_and_contacts"]["pairwise_cycles"]["nested_cv_epistasis"]["nested_cv_channels"]
    if summary_path.is_file():
        sdoc = json.loads(summary_path.read_text(encoding="utf-8"))
        assert any(a["arm"] == "esm3-1.4b" for a in sdoc["arms"])


def test_dplm_150m_diffusion_sampling_modes_gpu() -> None:
    """Verify uniform_random prevents homopolymer collapse and invalid modes fail fast."""
    import torch

    if not torch.cuda.is_available():
        pytest.skip("CUDA required for DPLM-150M sampling test")
    try:
        adapter = load_general_plm("dplm-150m", device="cuda:0", dtype="float32")
    except FileNotFoundError:
        pytest.skip("dplm-150m checkpoint not staged locally")

    with pytest.raises(ValueError, match="invalid sampling_mode"):
        adapter.sample_diffusion_full(60, seed=7, steps=8, sampling_mode="bogus_mode")

    res_rand = adapter.sample_diffusion_full(
        100, seed=42, steps=32, temperature=1.0, top_p=0.95, sampling_mode="uniform_random"
    )
    seq_rand = res_rand["sequence"]
    assert res_rand["sampling_mode"] == "uniform_random"
    assert len(seq_rand) == 100
    h_rand = _shannon_entropy_bits(seq_rand)
    max_aa_rand = max(collections.Counter(seq_rand).values()) / len(seq_rand)
    kmers_rand = [seq_rand[i : i + 5] for i in range(len(seq_rand) - 4)]
    dist5_rand = len(set(kmers_rand)) / len(kmers_rand)
    assert h_rand > 3.2, f"uniform_random unexpectedly low entropy: {h_rand:.3f}"
    assert max_aa_rand < 0.25, f"uniform_random homopolymer fraction too high: {max_aa_rand:.3f}"
    assert dist5_rand > 0.90, f"uniform_random low 5-mer diversity: {dist5_rand:.3f}"

    res_gumbel = adapter.sample_diffusion_full(
        60, seed=42, steps=16, temperature=1.0, top_p=0.95, sampling_mode="gumbel_annealed"
    )
    assert res_gumbel["sampling_mode"] == "gumbel_annealed"
    assert len(res_gumbel["sequence"]) == 60
